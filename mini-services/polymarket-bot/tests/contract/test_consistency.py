# Content-Type consistency
# ═══════════════════════════════════════════════════════════════════════════

class TestContentTypeConsistency:
    """Every JSON route must return ``Content-Type: application/json``
    (with optional ``; charset=utf-8`` suffix). A regression to
    ``text/plain`` would silently break the frontend's ``res.json()`` parse
    on some browsers (the WHATWG fetch spec is permissive, but a few older
    Safari versions still gate JSON parsing on the content-type header)."""

    @pytest.mark.parametrize("path", [
        "/api/health",
        "/api/status",
        "/api/positions",
        "/api/orders",
        "/api/trades",
        "/api/events",
        "/api/cache/stats",
        "/api/rate-limit/stats",
        "/api/observability",
        "/api/attribution",
    ])
    def test_content_type_is_application_json(self, client, auth_headers, path):
        resp = client.get(path, headers=auth_headers)
        assert resp.status_code == 200
        assert _content_type(resp) == "application/json", (
            f"{path} returned content-type "
            f"{resp.headers.get('content-type')!r}"
        )
