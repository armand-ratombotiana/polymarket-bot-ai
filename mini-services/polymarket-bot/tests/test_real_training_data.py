class TestTrainingDataStatusEndpoint:
    """Verify the ``GET /api/ml/training-data-status`` HTTP route."""

    @pytest.fixture
    def client(self):
        """Build a ``TestClient`` against a minimal FastAPI app with
        only the training-data-status route registered.

        Late-imports the production route handler from ``api.server``
        (which constructs the production FastAPI app at import time —
        the conftest env redirects make the heavy singleton init safe).
        We then add the SAME handler function on a fresh FastAPI app
        so the test isn't perturbed by the production app's middleware /
        dependency-injection graph.

        The handler closure captures ``ml_model`` from ``api.server``'s
        module scope, so it uses the same singleton the production
        route uses — monkey-patching ``ml_model._load_real_training_data``
        (or the underlying ``timescale_db`` singleton) is the lever the
        tests use to drive the route's branches.
        """
        from fastapi import FastAPI
        from fastapi.testclient import TestClient

        # Late import: triggers full ``api.server`` module load (the
        # conftest env redirects already point every *_DB_PATH env at
        # ``/tmp/pmbot_conftest_isolation``, so this is safe).
        from api.server import get_training_data_status

        fresh_app = FastAPI()
        fresh_app.add_api_route(
            "/api/ml/training-data-status",
            get_training_data_status,
            methods=["GET"],
        )
        return TestClient(fresh_app)

    def test_endpoint_returns_has_real_data_false_when_no_real_data(self, client):
        """When no real labeled samples are available, the endpoint
        returns ``has_real_data=False`` with zero counts. The route
        must NOT 500 — defensive try/except wraps the DB call."""
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (None, [])
            mock_db.fetch_labeled_feature_vectors.return_value = []
            resp = client.get("/api/ml/training-data-status")

        assert resp.status_code == 200, (
            f"expected 200, got {resp.status_code}: {resp.text}"
        )
        body = resp.json()
        assert body["has_real_data"] is False, (
            f"has_real_data must be False when no labeled samples, got {body['has_real_data']}"
        )
        assert body["n_samples"] == 0
        assert body["n_positive"] == 0
        assert body["n_negative"] == 0

    def test_endpoint_returns_has_real_data_true_when_data_available(self, client):
        """When ≥100 real labeled samples are available, the endpoint
        returns ``has_real_data=True`` with the correct sample count
        and class-balance breakdown."""
        X_real, y_real = _make_real_samples(n=150, n_positive=75)
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_real, y_real)
            resp = client.get("/api/ml/training-data-status")

        assert resp.status_code == 200, (
            f"expected 200, got {resp.status_code}: {resp.text}"
        )
        body = resp.json()
        assert body["has_real_data"] is True, (
            f"has_real_data must be True when ≥100 labeled samples available, "
            f"got {body['has_real_data']}"
        )
        assert body["n_samples"] == 150, (
            f"n_samples must be 150, got {body['n_samples']}"
        )
        assert body["n_positive"] == 75, (
            f"n_positive must be 75 (75 YES outcomes), got {body['n_positive']}"
        )
        assert body["n_negative"] == 75, (
            f"n_negative must be 75 (150 - 75 positive), got {body['n_negative']}"
        )

    def test_endpoint_reports_has_real_data_false_for_below_threshold(self, client):
        """When real labeled samples exist but fewer than 100,
        ``_load_real_training_data`` returns ``(None, None, None)``
        (per its threshold gate), so the endpoint returns
        ``has_real_data=False`` with zero counts — same shape as the
        no-data case. This is the documented W20-2 contract: the route
        can't tell apart "DB has 50 rows below threshold" from "DB is
        empty" because the underlying fetcher collapses both into
        ``(None, None, None)``. The operator inspects the DB directly
        (via ``GET /api/db/{table}``) for backfill progress."""
        X_few = np.zeros((50, N_FEATURES), dtype=np.float32)
        y_few = np.zeros(50, dtype=int)
        y_few[:25] = 1
        with patch("core.timescale_db.timescale_db") as mock_db:
            # fetch_training_samples returns 50 rows (below the 100
            # threshold), so the method falls through to the fallback.
            # fetch_labeled_feature_vectors returns [] (no fallback data)
            # so the method ultimately returns (None, None, None).
            mock_db.fetch_training_samples.return_value = (X_few, y_few)
            mock_db.fetch_labeled_feature_vectors.return_value = []
            resp = client.get("/api/ml/training-data-status")

        assert resp.status_code == 200
        body = resp.json()
        # Below the 100-row threshold → _load_real_training_data returns
        # (None, None, None), so the route surfaces zeros (mirrors the
        # no-data case — the threshold gate is inside the fetcher, not
        # the route).
        assert body["has_real_data"] is False, (
            f"has_real_data must be False below the 100-row threshold, "
            f"got {body['has_real_data']} (n_samples={body['n_samples']})"
        )
        assert body["n_samples"] == 0, (
            f"n_samples must be 0 when below threshold "
            f"(_load_real_training_data returns None), "
            f"got {body['n_samples']}"
        )
        assert body["n_positive"] == 0
        assert body["n_negative"] == 0


