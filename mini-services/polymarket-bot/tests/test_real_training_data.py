class TestLoadRealTrainingDataNoData:
    """Verify the no-data fallback path of ``_load_real_training_data``."""

    def test_returns_none_tuple_when_db_empty(self):
        """When both ``fetch_training_samples`` and
        ``fetch_labeled_feature_vectors`` return empty results,
        ``_load_real_training_data`` must return
        ``(None, None, None)`` — the documented contract that lets the
        caller decide its own fallback (synthetic vs. abort)."""
        m = MarketMLModel()
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (None, [])
            mock_db.fetch_labeled_feature_vectors.return_value = []
            features, labels, timestamps = m._load_real_training_data()

        assert features is None, (
            f"features must be None when DB has no labeled samples, "
            f"got {type(features).__name__} (shape={getattr(features, 'shape', None)})"
        )
        assert labels is None, (
            f"labels must be None when DB has no labeled samples, "
            f"got {type(labels).__name__} (len={len(labels) if labels is not None else 'n/a'})"
        )
        assert timestamps is None, (
            f"timestamps must be None when DB has no labeled samples, "
            f"got {type(timestamps).__name__}"
        )

    def test_returns_none_when_fewer_than_100_samples(self):
        """When the DB returns rows but fewer than 100, the method
        returns ``(None, None, None)`` — the ≥100 threshold is the
        documented gate so a 5-row cold-start DB doesn't produce a
        degenerate model fit."""
        m = MarketMLModel()
        # 50 rows — below the 100-row threshold.
        X_few = np.zeros((50, N_FEATURES), dtype=np.float32)
        y_few = np.zeros(50, dtype=int)
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_few, y_few)
            # Fallback also returns too few rows.
            mock_db.fetch_labeled_feature_vectors.return_value = [
                (X_few[i], int(y_few[i])) for i in range(50)
            ]
            features, labels, timestamps = m._load_real_training_data()

        assert features is None, (
            "features must be None when DB has <100 labeled samples "
            f"(got {len(features) if features is not None else 'None'})"
        )
        assert labels is None
        assert timestamps is None

    def test_falls_back_to_fetch_labeled_feature_vectors(self):
        """When ``fetch_training_samples`` returns too few rows BUT
        ``fetch_labeled_feature_vectors`` returns ≥100 rows, the method
        uses the fallback source. This exercises the second branch of
        the real-data fetcher (used when only one outcome class is
        labeled so far, so the stratified query can't fill its quota)."""
        m = MarketMLModel()
        X_real, y_real = _make_real_samples(n=120, n_positive=60)
        # fetch_training_samples returns empty (stratified query failed).
        # fetch_labeled_feature_vectors returns 120 rows (unstratified).
        fallback_samples = [(X_real[i], int(y_real[i])) for i in range(120)]
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (None, [])
            mock_db.fetch_labeled_feature_vectors.return_value = fallback_samples
            features, labels, timestamps = m._load_real_training_data()

        assert features is not None, (
            "features must NOT be None when fetch_labeled_feature_vectors "
            "returns ≥100 rows (fallback path)"
        )
        assert labels is not None
        assert timestamps is not None
        assert len(features) == 120, (
            f"expected 120 fallback rows, got {len(features)}"
        )
        assert len(labels) == 120
        assert len(timestamps) == 120
        # Labels preserve the 60/60 split from the source.
        assert int(np.sum(labels)) == 60


