# (3) get_training_data falls back to synthetic
# =============================================================================
class TestGetTrainingDataFallback:
    """Verify ``get_training_data`` prefers real, falls back to synthetic."""

    def test_returns_real_data_when_available(self):
        """When ``_load_real_training_data`` returns ≥100 rows,
        ``get_training_data`` returns them verbatim — no synthetic
        blend, no synthetic contamination of the labels."""
        m = MarketMLModel()
        X_real, y_real = _make_real_samples(n=200, n_positive=100)
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_real, y_real)
            features, labels, timestamps = m.get_training_data()

        # Real data path: 200 rows (not 3 000 — that would indicate the
        # synthetic fallback fired).
        assert features.shape == (200, N_FEATURES), (
            f"get_training_data should return real 200-row data, "
            f"got shape {features.shape} (likely synthetic fallback)"
        )
        assert len(labels) == 200
        assert int(np.sum(labels)) == 100

    def test_falls_back_to_synthetic_when_no_real_data(self):
        """When ``_load_real_training_data`` returns ``(None, None, None)``,
        ``get_training_data`` calls ``_synthetic_training_data(3000)`` and
        returns the synthetic arrays (with a placeholder timestamps
        array). This is the documented cold-start fallback path."""
        m = MarketMLModel()
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (None, [])
            mock_db.fetch_labeled_feature_vectors.return_value = []
            # Patch the synth generator to return 100 rows so the test
            # is fast (the production 3 000-row generator takes ~1s).
            with patch("ml.model._synthetic_training_data", _small_synth):
                features, labels, timestamps = m.get_training_data()

        # Synthetic fallback path: 100 rows (from the patched generator).
        assert features.shape == (100, N_FEATURES), (
            f"get_training_data synthetic fallback should return 100 rows, "
            f"got {features.shape}"
        )
        assert len(labels) == 100
        assert len(timestamps) == 100
        # Labels must be a 0/1 int array (synthetic generator output).
        assert set(np.unique(labels)).issubset({0, 1}), (
            f"synthetic labels must be 0/1, got unique values {np.unique(labels)}"
        )


