class TestLoadRealTrainingDataWithData:
    """Verify the happy path of ``_load_real_training_data``."""

    def test_returns_arrays_when_fetch_training_samples_has_data(self):
        """When ``fetch_training_samples`` returns ≥100 rows, the
        method returns the arrays verbatim (after dtype coercion to
        ``float32`` / ``int``) and synthesizes a placeholder
        monotonic-decreasing timestamps array of equal length."""
        m = MarketMLModel()
        X_real, y_real = _make_real_samples(n=150, n_positive=75)
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_real, y_real)
            features, labels, timestamps = m._load_real_training_data()

        assert features is not None
        assert labels is not None
        assert timestamps is not None
        # Shape preserved (n_samples × N_FEATURES).
        assert features.shape == (150, N_FEATURES), (
            f"expected features.shape=(150, {N_FEATURES}), got {features.shape}"
        )
        # Labels preserve the 75-positive / 75-negative split.
        assert len(labels) == 150
        assert int(np.sum(labels)) == 75, (
            f"expected 75 positive labels, got {int(np.sum(labels))}"
        )
        # Timestamps are a 1-D array of length n_samples.
        assert timestamps.shape == (150,), (
            f"expected timestamps.shape=(150,), got {timestamps.shape}"
        )
        # Placeholder timestamps are monotonic decreasing (rows are
        # most-recent-first from the SQL ``ORDER BY timestamp DESC``).
        assert np.all(np.diff(timestamps) < 0), (
            f"timestamps must be monotonically decreasing (rows are "
            f"most-recent-first), got {timestamps[:5]}..."
        )

    def test_pads_short_feature_vectors(self):
        """When the DB returns feature rows with fewer than N_FEATURES
        columns (legacy schema), the method pads them with zeros so the
        downstream ``scaler.fit_transform`` doesn't fail. Mirrors the
        same pad/trim behaviour that was in the prior ``fit_initial``
        blend path."""
        m = MarketMLModel()
        # 150 rows × (N_FEATURES - 5) columns — simulates a legacy
        # schema with 5 missing feature columns.
        short_n = N_FEATURES - 5
        X_short = np.zeros((150, short_n), dtype=np.float32)
        X_short[:, 0] = 0.5  # mid_price
        y_short = np.zeros(150, dtype=int)
        y_short[:75] = 1
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_short, y_short)
            features, labels, timestamps = m._load_real_training_data()

        assert features is not None
        assert features.shape == (150, N_FEATURES), (
            f"padded features must have {N_FEATURES} columns, got {features.shape[1]}"
        )

    def test_trims_long_feature_vectors(self):
        """When the DB returns feature rows with MORE than N_FEATURES
        columns (forward-compat with a schema that added new columns
        before the model was retrained on them), the method trims to
        ``N_FEATURES``."""
        m = MarketMLModel()
        long_n = N_FEATURES + 3
        X_long = np.zeros((150, long_n), dtype=np.float32)
        X_long[:, 0] = 0.5
        y_long = np.zeros(150, dtype=int)
        y_long[:75] = 1
        with patch("core.timescale_db.timescale_db") as mock_db:
            mock_db.fetch_training_samples.return_value = (X_long, y_long)
            features, labels, timestamps = m._load_real_training_data()

        assert features is not None
        assert features.shape == (150, N_FEATURES), (
            f"trimmed features must have {N_FEATURES} columns, got {features.shape[1]}"
        )


