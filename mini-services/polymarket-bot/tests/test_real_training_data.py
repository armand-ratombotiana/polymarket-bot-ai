class TestFitInitialPrefersRealData:
    """Verify ``fit_initial`` uses real-only training when ≥100 real
    labeled samples are available, and synthetic-only as cold-start
    fallback."""

    def test_fit_initial_trains_on_real_data_when_available(self):
        """When ≥100 real labeled samples are available, ``fit_initial``
        sets ``training_source == "real_only"``, ``n_real_samples >= 100``,
        and ``n_synthetic_samples == 0`` (no blend — the W20-2 contract)."""
        X_real, y_real = _make_real_samples(n=200, n_positive=100)
        with patch("core.timescale_db.timescale_db") as mock_db, \
             patch("ml.model._synthetic_training_data", _small_synth):
            mock_db.fetch_training_samples.return_value = (X_real, y_real)
            m = MarketMLModel()
            # Smaller estimator counts keep wall-time tractable.
            m.fit_initial(n_estimators_rf=10, n_estimators_gb=10)

        assert m.training_source == "real_only", (
            f"training_source must be 'real_only' when ≥100 real samples "
            f"are available, got {m.training_source!r}"
        )
        assert m.n_real_samples == 200, (
            f"n_real_samples must be 200 (count of real rows used), "
            f"got {m.n_real_samples}"
        )
        assert m.n_synthetic_samples == 0, (
            f"n_synthetic_samples must be 0 in the real-only branch "
            f"(no blend), got {m.n_synthetic_samples}"
        )
        # Belt-and-braces: model is fitted.
        assert m.is_fitted is True, (
            "is_fitted must be True after a successful fit_initial"
        )

    def test_fit_initial_falls_back_to_synthetic_when_no_real_data(self):
        """When no real labeled samples are available, ``fit_initial``
        falls back to synthetic-only training — sets
        ``training_source == "synthetic_only"``, ``n_real_samples == 0``,
        ``n_synthetic_samples > 0``. This is the cold-start fallback
        that keeps the predict path functional before the backfill loop
        has populated the SQLite store."""
        with patch("core.timescale_db.timescale_db") as mock_db, \
             patch("ml.model._synthetic_training_data", _small_synth):
            mock_db.fetch_training_samples.return_value = (None, [])
            mock_db.fetch_labeled_feature_vectors.return_value = []
            m = MarketMLModel()
            m.fit_initial(n_estimators_rf=10, n_estimators_gb=10)

        assert m.training_source == "synthetic_only", (
            f"training_source must be 'synthetic_only' when no real data, "
            f"got {m.training_source!r}"
        )
        assert m.n_real_samples == 0, (
            f"n_real_samples must be 0 in the synthetic-only branch, "
            f"got {m.n_real_samples}"
        )
        assert m.n_synthetic_samples > 0, (
            f"n_synthetic_samples must be > 0 in the synthetic-only branch, "
            f"got {m.n_synthetic_samples}"
        )
        assert m.is_fitted is True

    def test_fit_initial_real_only_does_not_blend_synthetic(self):
        """Critical correctness invariant: when real data is available,
        the synthetic generator is NOT called at all. This is the
        structural fix for the God Mode W17-3 C1 finding (synthetic
        labels contaminating the training set). Verified by spying on
        ``_synthetic_training_data`` and asserting it was never called
        in the real-data branch."""
        X_real, y_real = _make_real_samples(n=200, n_positive=100)
        # Use a side_effect that raises if called — proves the
        # synthetic generator was NOT invoked.
        def _synth_should_not_be_called(*args, **kwargs):
            raise AssertionError(
                "_synthetic_training_data must NOT be called when real "
                "labeled samples are available (W20-2 real-only contract)"
            )
        with patch("core.timescale_db.timescale_db") as mock_db, \
             patch("ml.model._synthetic_training_data", _synth_should_not_be_called):
            mock_db.fetch_training_samples.return_value = (X_real, y_real)
            m = MarketMLModel()
            # Must complete without the patched synth generator firing.
            m.fit_initial(n_estimators_rf=10, n_estimators_gb=10)

        assert m.training_source == "real_only"
        assert m.n_real_samples == 200
        assert m.n_synthetic_samples == 0
