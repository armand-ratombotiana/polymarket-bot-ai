"""
tests/test_real_training_data.py — W20-2 real-data ML training path.

Covers the 5 behaviours required by the W20-2 task spec:

  (1) ``MarketMLModel._load_real_training_data`` returns
      ``(None, None, None)`` when no real labeled samples are available
      (both ``fetch_training_samples`` and
      ``fetch_labeled_feature_vectors`` return empty).

  (2) ``MarketMLModel._load_real_training_data`` returns populated numpy
      arrays when real labeled samples are available (mocked
      ``fetch_training_samples`` returning ≥100 rows).

  (3) ``MarketMLModel.get_training_data`` falls back to the synthetic
      generator (3 000 rows) when no real data is available, and
      prefers real data when it is.

  (4) HTTP route ``GET /api/ml/training-data-status`` returns
      ``has_real_data=False`` when no real data is available, and
      ``has_real_data=True`` with correct class counts when real data
      exists (mocked).

  (5) ``MarketMLModel.fit_initial`` prefers real data — when ≥100 real
      labeled samples are available, ``training_source == "real_only"``
      and ``n_synthetic_samples == 0`` (no blend). When no real data is
      available, it falls back to synthetic-only training.

God Mode assessment context (W17-3, C1)
~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
The prior ``fit_initial`` blended 3 000 synthetic samples with real DB
samples when available. The synthetic labels are generated by a
hand-coded log-odds formula over the SAME feature columns the model is
trained on, so a model trained on the blend trivially "predicts" the
synthetic labels — structurally inflating Brier / AUC metrics. The W20-2
real-first policy eliminates that circularity: real data trains real,
synthetic is cold-start fallback only.

Mock strategy
~~~~~~~~~~~~~
  * ``mock_db`` — a ``MagicMock`` placed on ``core.timescale_db.timescale_db``
    via ``patch("core.timescale_db.timescale_db")``. The late import
    inside ``_load_real_training_data`` re-resolves the
    ``core.timescale_db.timescale_db`` attribute at call time, so the
    patch is picked up by the production code path. ``fetch_training_samples``
    and ``fetch_labeled_feature_vectors`` are configured per-test via
    ``mock_db.fetch_training_samples.return_value`` /
    ``mock_db.fetch_labeled_feature_vectors.return_value``.

  * ``_small_synth`` — patched ``ml.model._synthetic_training_data`` so
    a ``fit_initial`` call uses 100 rows (not the production 3 000) and
    keeps the per-test wall-time tractable (mirrors the ``fitted_model``
    fixture pattern in ``tests/test_ml_model.py``).

Sync ``def`` tests throughout — ``TestClient``'s sync portal manages the
FastAPI event loop for the HTTP route test (no ``pytestmark =
pytest.mark.asyncio`` needed, mirrors the convention in
``tests/test_feature_store.py`` / ``tests/test_ab_testing.py`` /
``tests/test_explainability.py``).
"""
