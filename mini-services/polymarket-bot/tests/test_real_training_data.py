def _make_real_samples(n: int = 150, n_positive: int = 75) -> tuple[np.ndarray, np.ndarray]:
    """Build a controlled ``n``-row synthetic-but-realistic feature/label pair.

    The features are random uniform in ``[0, 1]`` per cell (so they're
    well-formed 38-dim vectors for ``scaler.fit_transform``), and the
    labels are a hand-crafted mix of 0s and 1s so the class-balance
    assertions in the HTTP route test are deterministic.

    Not the same as ``_synthetic_training_data`` (which generates labels
    via the log-odds formula) — these labels are arbitrary but
    deterministic, exercising ONLY the data-loading plumbing, not the
    model's fit quality.

    The labels are INTERLEAVED (shuffled) across the row axis so the
    time-ordered 80/20 split in ``fit_initial`` puts both classes in
    BOTH the train fold and the calibration fold. Without the shuffle,
    the first ``n_positive`` rows are all 1 and the rest are all 0 —
    so the train fold would be all-1 and the calibration fold all-0,
    which trips ``roc_auc_score``'s "need classifier with two classes"
    guard (the classifier was trained on a single-class target).
    """
    rng = np.random.RandomState(42)
    X = rng.uniform(0.0, 1.0, (n, N_FEATURES)).astype(np.float32)
    y = np.zeros(n, dtype=int)
    y[:n_positive] = 1
    # Interleave the labels so both classes appear in both folds of the
    # 80/20 time-ordered split (defensive against single-class folds).
    perm = rng.permutation(n)
    X = X[perm]
    y = y[perm]
    return X, y


def _small_synth(n: int = 100) -> tuple[np.ndarray, np.ndarray]:
    """100-row synthetic generator (mirrors the ``fitted_model`` fixture
    pattern in ``tests/test_ml_model.py``)."""
    return _synthetic_training_data(100)


